const fs=require('node:fs');
fs.mkdirSync('public/contracts',{recursive:true});
for(const [contract,file,constant] of [['RaqioVault','vault-abi','RAQIO_VAULT_ABI'],['RaqioAirdrop','airdrop-abi','RAQIO_AIRDROP_ABI'],['RaqioScore','score-abi','RAQIO_SCORE_ABI']]){
 const artifact=JSON.parse(fs.readFileSync(`contracts/out/${contract}.sol/${contract}.json`,'utf8'));
 fs.writeFileSync(`src/lib/contracts/${file}.ts`,`// Generated by scripts/sync-contract-abis.cjs from compiled Solidity.\nexport const ${constant} = ${JSON.stringify(artifact.abi,null,2)} as const;\n`);
 fs.writeFileSync(`public/contracts/${contract}.abi.json`,JSON.stringify(artifact.abi,null,2)+'\n');
}
console.log('Synced vault, airdrop and score ABIs from compiled artifacts.');
